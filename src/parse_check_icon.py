"""
parse_check_icon.py

Parses ICON `make check-icon` output (PASS/SKIP/FAIL lines)
and converts it into a structured pandas DataFrame.
"""

import re
import pandas as pd


LINE_PATTERN = re.compile(r"^(PASS|FAIL|SKIP):\s+(\S+)\s*$")


def parse_check_icon_output(text: str) -> pd.DataFrame:
    """Parse raw `make check-icon` output text into a DataFrame."""
    rows = []
    for line in text.splitlines():
        match = LINE_PATTERN.match(line.strip())
        if not match:
            continue
        result, test_full = match.groups()

        if "." in test_full:
            name, variant = test_full.rsplit(".", 1)
            if variant not in ("mpi", "nompi"):
                name, variant = test_full, "plain"
        else:
            name, variant = test_full, "plain"

        rows.append({"test_name": name, "variant": variant, "result": result})

    return pd.DataFrame(rows)


def load_synthetic_csv(path: str) -> pd.DataFrame:
    """Load the synthetic CSV generated by generate_data.py."""
    return pd.read_csv(path)


